"""Step 13: AUDIT_SUMMARY.md, a plain-text audit of every phase with real numbers and example rows.

Reads the finished files in data/out/ and writes AUDIT_SUMMARY.md in the project folder. Nothing is
hard-coded: rerun it after any pipeline run and the numbers follow.
"""
import json
import re

import pandas as pd

import config

OUT, STATS, FIG = config.OUT_DIR, config.OUT_DIR / "stats", config.OUT_DIR / "figures"
INSTS = list(config.INSTITUTES)
lines = []


def w(*a):
    lines.extend(a)


def table(df, **kw):
    return df.to_markdown(index=False, **kw) if hasattr(df, "to_markdown") else df.to_string(index=False)


def block(text):
    w("```text", text.rstrip(), "```", "")


def main():
    m = pd.read_csv(OUT / "group15_data.csv", dtype=str, keep_default_na=False)
    p = pd.read_csv(OUT / "papers_enriched.csv", dtype=str, keep_default_na=False)
    ff = pd.read_csv(config.ROOT / "data" / "faculty_final.csv", dtype=str, keep_default_na=False)
    pub = json.load(open(STATS / "publication_results.json"))
    net = json.load(open(STATS / "network_results.json"))
    fnet = json.load(open(STATS / "faculty_network_results.json"))
    n = len(m)

    w("# Group 15 audit summary", "",
      "Institutes: MANIT Bhopal, NIT Jamshedpur, NIT Silchar. Years 2016-2026 (2026 is a partial year). "
      "Generated by `audit_summary.py` from the files in `data/out/`.", "")

    # ------------------------------------------------------------------ phase 1
    w("## Phase 1: dataset creation and faculty verification", "")
    br = (OUT / "build_report.txt").read_text().splitlines()
    block("\n".join(x for x in br if x.startswith(("Unique works", "Dropped", "Papers kept", "Papers per type"))))
    fac_rows = m[m.is_faculty == "TRUE"]
    block(f"""faculty list (faculty_final.csv): {len(ff)} people
{ff.groupby(['institution', 'faculty_status']).size().unstack(fill_value=0).to_string()}
how they got on the list: {ff.source.value_counts().to_dict()}
matched to OpenAlex papers: {int((ff.match_status == 'matched').sum())} | no papers found: {int((ff.match_status == 'not_found').sum())}

group15_data.csv rows (faculty authors only): {n} | distinct papers: {m.openalex_work_id.nunique()}
authors that are not faculty (PhD scholars, staff, visitors, collaborators who print our name) were removed:
  {int(pd.read_csv(OUT / 'all_authors' / 'group15_data.csv', usecols=['is_faculty'], dtype=str).is_faculty.ne('TRUE').sum())} rows dropped""")
    if (OUT / "all_authors" / "group15_data.csv").exists():
        a = pd.read_csv(OUT / "all_authors" / "group15_data.csv", usecols=["author_role", "is_faculty"], dtype=str)
        block("author roles in the unfiltered table (OpenAlex evidence + official pages):\n" + a.author_role.value_counts().to_string())
    big = m.drop_duplicates("openalex_work_id")
    big = big[big.is_multi_author_10plus == "TRUE"]
    d10 = pd.read_csv(STATS / "multi_author_10plus_papers.csv")
    block(f"papers with more than 10 authors flagged (is_multi_author_10plus): {len(big)}\n"
          f"  our faculty on them: {d10.n_our_faculty.sum()} author slots, non-faculty removed: {int(d10.n_our_non_faculty_removed.sum())}\n"
          f"  review flags (former outside page years / record mostly elsewhere): {int((d10.review_flags.fillna('') != '').sum())}\n"
          f"  most authors on one paper in the data: {int(d10.n_authors.max())}")
    w("Example faculty rows:", "")
    block(ff[["institution", "name", "department", "designation", "faculty_status", "papers", "verification"]].head(4).to_string(index=False))

    # ------------------------------------------------------------------ phase 2
    w("## Phase 2: schema, quartiles, hygiene", "")
    need = ["group", "institution", "author", "title", "year", "type", "journal_name", "issn", "doi", "citations", "quartile",
            "coauthor_institutes", "cites_indian_inst", "cited_by_indian_inst"]
    blanks = {c: int((m[c] == "").sum()) for c in m.columns if (m[c] == "").any()}
    pp = m.drop_duplicates("openalex_work_id")
    block(f"required columns present: {not set(need) - set(m.columns)} | group = {sorted(m.group.unique())} | years {m.year.min()}-{m.year.max()} | "
          f"types {sorted(m.type.unique())}\n"
          f"DOIs in https://doi.org/ form: {m[m.doi != ''].doi.str.startswith('https://doi.org/').mean():.1%}\n"
          f"empty cells (rows): {blanks}\n"
          f"duplicate (paper, faculty, institute) rows: {int(m.duplicated(['openalex_work_id', 'faculty_name', 'institution']).sum())} | "
          f"duplicate DOIs among papers: {int(pp[pp.doi != ''].doi.duplicated().sum())}")
    t = p.assign(t=p.title.map(lambda s: re.sub(r'[^a-z0-9]+', ' ', s.lower()).strip()))
    dup = t[t.duplicated(['t', 'year'], keep=False)].groupby(['t', 'year']).ngroups
    w(f"Same title and year under two DOIs (journal and its early-access copy, mostly Inderscience): {dup} pairs. "
      "Kept as they are; they are separate OpenAlex records with their own DOI.", "")
    qs = m.drop_duplicates("openalex_work_id")
    block("quartile / rank by source (papers):\n" + pd.crosstab(qs.type, qs.quartile_source).to_string() + "\n\nquartile values:\n" + qs.quartile.value_counts().to_string())
    w("`sjr_approx` = SCImago SJR recomputed, `scopus_citescore` = Scopus CiteScore percentile, `core` = CORE 2023, "
      "`estimated_openalex` / `estimated_publisher` = estimated (58% exact, 96% within one quartile when tested), `none` = Unranked.", "")
    block(f"high-impact flags (journal Q1 and the lower of SCImago citations/doc and OpenAlex 2-year citedness): Q1 and >5: {int((qs.q1_impact_gt5 == 'TRUE').sum())} papers, "
          f"Q1 and >10: {int((qs.q1_impact_gt10 == 'TRUE').sum())} papers")

    # ------------------------------------------------------------------ phase 3
    w("## Phase 3: networks", "")
    c = net["citation_network"]
    block(f"citation_network.csv: {c['edges']} edges between {c['nodes_in_edges']} papers; within one institute {c['edges_within_same_institute']}, "
          f"across institutes {c['edges_cross_institute']}\n"
          f"max in-degree {c['in_degree_max']}; top PageRank paper: {c['top10_pagerank'][0]}")
    aa = net["authorship_network_core_authors"]
    block(f"authorship_network.csv: {net['authorship_network_meta']['pair_rows_in_file']} author pairs; core-author graph {aa['nodes']} nodes, "
          f"{aa['edges']} edges, {aa['louvain_communities']} Louvain communities (modularity {aa['louvain_modularity']})\n"
          f"top betweenness: {aa['top10_betweenness'][:3]}")
    wn = fnet["whole_network"]
    block(f"faculty co-authorship network: {wn['nodes']} faculty, {wn['edges']} links, {wn['isolated_faculty']} isolated, "
          f"cross-department {wn['cross_department_edges_%']}%, cross-institute links {wn['cross_institute_edges']}")
    ic = pd.read_csv(OUT / "indian_connections.csv")
    w("indian_connections.csv, top partner institutes per institute:", "")
    block(ic.sort_values(["your_inst", "shared_papers"], ascending=[True, False]).groupby("your_inst").head(3).to_string(index=False))
    cr = pd.read_csv(STATS / "citation_ratio.csv")
    block("incoming / outgoing citations (other Indian institutes), 2016-2026:\n" + cr[cr.year == "2016-2026"].drop(columns="year").to_string(index=False))

    # ------------------------------------------------------------------ phase 4
    w("## Phase 4: statistics", "")
    block("papers per year:\n" + pd.read_csv(STATS / "papers_per_year.csv", index_col=0).to_string())
    q = pd.DataFrame({i: v["shares_%"] for i, v in pub["quartiles"].items()}).T
    q["Q1_fraction_%"] = [pub["quartiles"][i]["Q1_fraction_%"] for i in q.index]
    q["unranked_journal_papers"] = [pub["quartiles"][i]["unranked"] for i in q.index]
    block("journal quartile share (%), papers with a quartile:\n" + q.to_string())
    block("conference ranks:\n" + pd.DataFrame(pub["conference_rank"]).T[["conference_papers", "with_CORE_rank", "rank_counts", "with_scopus_quartile", "unranked"]].to_string())
    for i in INSTS:
        block(f"top 5 journals, {i}:\n" + pd.read_csv(STATS / f"top_journals_{i.replace(' ', '_')}.csv").head(5).to_string(index=False))
    t30 = pd.read_csv(STATS / "top30_summary.csv")
    w("Top 30 papers per institute (`top30_papers_<institute>.csv`):", "")
    block(t30.T.to_string(header=False))
    ma = pd.read_csv(STATS / "multi_author_reanalysis.csv")
    w("Re-analysis without the papers that have more than 10 authors:", "")
    block(ma[["institution", "scope", "papers", "citations", "journal_Q1_share_%", "median_faculty_h", "faculty_h_20_plus"]].to_string(index=False))
    w("Author-level (faculty): `faculty_ranking_<institute>.csv`, `h_index_distribution.csv`, `author_brokers.csv`, `author_analysis.json`.", "")
    block(pd.read_csv(STATS / "h_index_distribution.csv").pivot(index="h_index", columns="institution", values="faculty")
          .reindex(["0", "1-4", "5-9", "10-14", "15-19", "20-29", "30+"]).to_string())
    for i in INSTS:
        g = pd.read_csv(STATS / f"faculty_ranking_{i.replace(' ', '_')}.csv").head(5)
        block(f"top 5 faculty by h-index, {i}:\n" + g[["faculty_name", "department", "papers", "citations", "h_index", "q1_papers", "top_journal"]].to_string(index=False))

    # extra metrics from the checklist
    mac = json.load(open(STATS / "citation_network_macro.json"))["whole corpus"]
    block("citation network (papers): " + str({k: v for k, v in mac.items() if not k.startswith("top")}) +
          "\n  metrics per paper in citation_node_metrics.csv: in-degree, out-degree, PageRank, HITS authority / hub, in-degree h-index")
    fx = json.load(open(STATS / "faculty_network_extra.json"))
    block("faculty network (diameter, shortest path, assortativity, k-core):\n" + pd.DataFrame(fx).to_string(index=False))
    block("bridge authors (co-authorship edges to other Indian institutes), top 2 per institute:\n" +
          pd.read_csv(STATS / "bridge_authors.csv").groupby("institution").head(2).to_string(index=False))
    block("institute summary:\n" + pd.read_csv(STATS / "institution_summary.csv").set_index("institution").T.to_string())
    block("papers with more than 10 authors vs the rest:\n" + pd.read_csv(STATS / "hyper_authorship_performance.csv").to_string(index=False))

    # ------------------------------------------------------------------ phase 5 inputs
    w("## Phase 5: files the dashboard reads", "")
    block("figures (data/out/figures/):\n" + "\n".join(f"  {f.name}" for f in sorted(FIG.glob('*.png'))) +
          "\n\ntables (data/out/ and data/out/stats/):\n" + "\n".join(
              f"  {f.relative_to(OUT)}" for f in sorted(list(OUT.glob("*.csv")) + list(STATS.glob("*.csv")) + list(STATS.glob("*.json")))
              if f.stat().st_size < 30_000_000))

    w("## Known limits", "",
      "- Quartiles marked `estimated_*` are estimates, not official ranks. IF > 5 and IF > 10 use the lower of SCImago citations per document and OpenAlex 2-year mean citedness (cross-checked, since SCImago alone overstates new journals), not the Clarivate impact factor.",
      f"- {int((m.quartile == 'Unranked').sum())} rows (papers without DOI or venue) are Unranked; {int(m.doi.eq('').sum())} rows have no DOI.",
      "- No paper in the data has more than 30 authors (OpenAlex download). Large collaborations may be missing: to be checked with `authors_count` filters.",
      "- Partner statistics (`partners.py`) and 5.8% of reference lists (`links.py refs`) need the OpenAlex daily budget and may be older than the rest.")
    (config.ROOT / "AUDIT_SUMMARY.md").write_text("\n".join(lines))
    print("wrote AUDIT_SUMMARY.md,", len(lines), "lines")


if __name__ == "__main__":
    main()
